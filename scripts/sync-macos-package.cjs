const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const target = path.join(root, "macos/package.json");
const sorted = object => Object.fromEntries(Object.entries(object).sort(([a], [b]) => a.localeCompare(b, "en")));

function generate(rootPackage, overrides) {
  const codegen = structuredClone(rootPackage.codegenConfig);
  codegen.jsSrcsDir = `../${codegen.jsSrcsDir}`;
  const patches = { ...rootPackage.patchedDependencies, ...overrides.patchedDependencies };
  return {
    name: `${rootPackage.name}-macos`,
    version: rootPackage.version,
    private: true,
    description: "GENERATED by scripts/sync-macos-package.cjs. Edit root package.json or macos/dependency-overrides.json instead.",
    scripts: {
      "check:sync": "node ../scripts/sync-macos-package.cjs --check",
      preinstall: "node ../scripts/sync-macos-package.cjs --check",
      postinstall: "node node_modules/react-native-turbo-lnd/fetch-lnd.js --targets=macos",
      start: "node cli.cjs start --config metro.config.js",
      bundle: "node cli.cjs bundle --platform macos --config metro.config.js --entry-file index.js --dev false --bundle-output build/main.jsbundle --assets-dest build",
      "mainnet-debug": 'node cli.cjs run-macos --scheme "BlixtWallet Mainnet" --mode Debug',
      mainnet: 'node cli.cjs run-macos --scheme "BlixtWallet Mainnet" --mode Release',
      "regtest-debug": 'node cli.cjs run-macos --scheme "BlixtWallet Regtest" --mode "Debug Regtest"',
      regtest: 'node cli.cjs run-macos --scheme "BlixtWallet Regtest" --mode "Release Regtest"',
    },
    dependencies: sorted({ ...rootPackage.dependencies, ...overrides.dependencies }),
    devDependencies: sorted({ ...rootPackage.devDependencies, ...overrides.devDependencies }),
    engines: rootPackage.engines,
    codegenConfig: codegen,
    patchedDependencies: sorted(Object.fromEntries(Object.entries(patches).map(([name, file]) => [name, `../${file}`]))),
  };
}

function sync(check = false) {
  const manifest = generate(
    JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8")),
    JSON.parse(fs.readFileSync(path.join(root, "macos/dependency-overrides.json"), "utf8")),
  );
  const expected = JSON.stringify(manifest, null, 2) + "\n";
  if (check) {
    if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== expected) {
      throw new Error("macos/package.json is stale. Run bun run macos:sync, then bun run macos:install and commit macos/package.json and macos/bun.lock.");
    }
  } else {
    fs.writeFileSync(target, expected);
  }
}
if (require.main === module) {
  try { sync(process.argv.includes("--check")); }
  catch (error) { console.error(error.message); process.exitCode = 1; }
}
module.exports = { generate, sync };
